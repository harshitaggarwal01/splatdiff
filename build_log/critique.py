def gather(round2: bool = False) -> str:
    parts = []
    files = ["PRODUCT.md", "README.md", "VIDEO_SCRIPT.md", "build_log/SUBMISSION_DRAFT.md"]
    if round2:
        files += ["web/home.html", "build_log/critique_wonder.md", "build_log/critique_spark.md"]
    for rel in files:
        p = ROOT / rel
        if p.exists():
            parts.append(f"===== {rel} =====\n{p.read_text(encoding='utf-8')}")
    parts.append(
        "===== UI (current) =====\nCare dossier web UI: masthead 'What changed in Mom's room since your last visit?'; "
        "intake with 'Last visit' / 'Today' video drop zones, 'Must stay put' watchlist tags, 'Speak your care notes' "
        "voice button, 'Use the sample room'; live 'The check, as it happens' stage list with filmstrips, concept chips "
        "with L/T marks, 'Learning the family's words' (vocabulary repair), re-check, moved judge, report, grounding "
        "filter; report with summary, Care watchlist, 'What changed' findings sorted by risk with Evidence boards "
        "(before/after frames with SAM boxes + evidence table), 'Struck from the report' with an ink-strike animation, "
        "ledger of models/cost, Print for family, Copy summary, Past checks drawer."
    )
    return "\n\n".join(parts)


def main():
    who = sys.argv[1] if len(sys.argv) > 1 else "wonder"
    cfg = PERSONAS[who]
    body = {
        "model": cfg["model"],
        "input": [{"role": "user", "content": (
            f"{cfg['role']}\n\n{QUESTIONS2 if who.endswith('2') else QUESTIONS}\n\n"
            f"# MATERIAL\n{gather(who.endswith('2'))}")}],
        "stream": True,
        "max_output_tokens": 16000,
        "reasoning": {"effort": cfg["effort"]},
        "tools": [{"type": "web_search"}],
    }
    headers = {
        "Authorization": f"Bearer {os.environ['MODEL_API_KEY']}",
        "Content-Type": "application/json",
        "Accept": "text/event-stream",
    }
    t0 = time.time()
    r = requests.post("https://api.meta.ai/v1/responses", headers=headers, json=body, stream=True, timeout=900)
    if r.status_code != 200:
        print(r.status_code, r.text[:1500])
        sys.exit(1)
    out = []
    for line in r.iter_lines():
        if not line:
            continue
        s = line.decode("utf-8", "replace")
        if not s.startswith("data: ") or s[6:].strip() == "[DONE]":
            continue
        try:
            ev = json.loads(s[6:])
        except json.JSONDecodeError:
            continue
        if ev.get("type") == "response.output_text.delta":
            out.append(ev.get("delta", ""))
        elif ev.get("type") in ("error", "response.failed"):
            print("ERROR EVENT:", s[:1500])
    text = "".join(out)
    dest = ROOT / "build_log" / f"critique_{who}.md"
    dest.write_text(f"# Critique by {cfg['model']}\n\n{text}\n", encoding="utf-8")
    print(f"{who}: {len(text)} chars in {time.time()-t0:.0f}s -> {dest.name}")


if __name__ == "__main__":
    main()
